// Writes src/styles/palettes.ts from tweakcn's registry: each theme's colours in both modes, its corner radius and
// its fonts, plus the three of our own in palettes.own.json. Shadows are left out. Run it to pick up new themes:
//   bun scripts/palettes.mjs && bunx biome check --write src/styles/palettes.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SOURCE = "https://tweakcn.com/r/registry.json";
const KEYS = [
  "background",
  "foreground",
  "card",
  "card-foreground",
  "popover",
  "popover-foreground",
  "primary",
  "primary-foreground",
  "secondary",
  "secondary-foreground",
  "muted",
  "muted-foreground",
  "accent",
  "accent-foreground",
  "destructive",
  "destructive-foreground",
  "border",
  "input",
  "ring",
];
// The values end up in a style element, so only what a colour or a length can be gets through.
const COLOUR = /^oklch\(\d*\.?\d+ \d*\.?\d+ \d*\.?\d+\)$/;
const RADIUS = /^\d*\.?\d+(rem|px)$/;
const NAME = /^[a-z0-9-]+$/;
const TITLE = /^[\w .'&-]+$/;
const STACK = /^[\w ,'"-]+$/;
const FAMILY = /^[A-Za-z0-9 ]{1,40}$/;
// What a stack may start with that the reader's machine already has. Any other first family is fetched from Google Fonts.
const LOCAL =
  /^(ui-.*|system-ui|-apple-system|BlinkMacSystemFont|serif|sans-serif|monospace|Georgia|Menlo|Courier New|Arial|Times New Roman|Helvetica|Berkeley Mono)$/;

const need = (pattern, value, what) => {
  if (typeof value !== "string" || !pattern.test(value)) {
    throw new Error(`${what} is ${JSON.stringify(value)}, which isn't what a palette may hold`);
  }
  return value;
};
const colours = (vars, what) => Object.fromEntries(KEYS.map(key => [key, need(COLOUR, vars[key], `${what} ${key}`)]));

function fonts(vars, what) {
  // A name like Source Serif 4 isn't valid CSS unquoted, so every family that isn't one plain word gets quotes.
  const families = stack => stack.split(",").map(family => family.trim().replace(/^['"]|['"]$/g, ""));
  const quoted = family => (/^-?[A-Za-z][\w-]*$/.test(family) ? family : `"${family}"`);
  const stacks = Object.fromEntries(
    ["sans", "serif", "mono"].map(kind => [
      kind,
      families(need(STACK, vars[`font-${kind}`], `${what} font-${kind}`))
        .map(quoted)
        .join(", "),
    ]),
  );
  const first = Object.values(stacks).map(stack => families(stack)[0]);
  const load = [...new Set(first.filter(family => !LOCAL.test(family)))].map(family => need(FAMILY, family, `${what} font family`));
  return { fonts: stacks, load };
}

export const palette = item => ({
  name: need(NAME, item.name, "name"),
  title: need(TITLE, item.title, `${item.name} title`),
  radius: need(RADIUS, item.cssVars.light.radius, `${item.name} radius`),
  light: colours(item.cssVars.light, `${item.name} light`),
  dark: colours(item.cssVars.dark, `${item.name} dark`),
  ...fonts(item.cssVars.light, item.name),
});

if (import.meta.main) {
  const response = await fetch(SOURCE);
  if (!response.ok) {
    throw new Error(`${SOURCE} answered ${response.status}`);
  }
  const { items } = await response.json();
  // Three of our own, in the registry's shape: GitHub, Grafana and Linear, from each product's published colours.
  const own = JSON.parse(readFileSync(join(import.meta.dir, "palettes.own.json"), "utf8"));
  // By name, so one can be found without reading the list.
  const list = [...own, ...items].map(palette).sort((a, b) => a.title.localeCompare(b.title));
  const body = `import type { Palette } from "src/utils/palette";

// Generated by scripts/palettes.mjs from ${SOURCE}. Don't edit it by hand.
export const PALETTES: Palette[] = ${JSON.stringify(list, null, 2)};
`;
  writeFileSync(join(import.meta.dir, "../src/styles/palettes.ts"), body);
  console.log(`${list.length} palettes written`);
}
